import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import * as all from 'ionicons/icons';

const files = [];
const walk = (d) => readdirSync(d).forEach((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : /\.(ts|html)$/.test(f) && files.push(join(d, f))));
walk('src/app');
const names = new Set();
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
for (const f of files) {
  if (f.endsWith('icons.ts')) continue;
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(/(?:name|icon|pullingIcon|iconActive)\s*[:=]\s*["'`]([a-z0-9-]+)["'`]/g)) names.add(m[1]);
  for (const m of src.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)+)['"`]/g)) if (all[camel(m[1])]) names.add(m[1]);
  for (const m of src.matchAll(/['"`]([a-z]+)['"`]/g)) if (all[m[1]] && /icon|name/i.test(src.slice(Math.max(0, m.index - 40), m.index))) names.add(m[1]);
}
const ids = [...names].map(camel).filter((n) => all[n]).sort();
const out = `import { addIcons } from 'ionicons';\nimport {\n${ids.map((i) => `  ${i},`).join('\n')}\n} from 'ionicons/icons';\n\n/** Generated by scripts/gen-icons.mjs — only the icons the app uses. */\nexport function registerIcons(): void {\n  addIcons({\n${ids.map((i) => `    ${i},`).join('\n')}\n  });\n}\n`;
writeFileSync('src/app/icons.ts', out);
console.log(ids.length, 'icons');
